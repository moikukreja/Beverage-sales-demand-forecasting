import { useState } from "react";
import { BarChart3, Database, Layers, LineChart, Sparkles, TrendingUp, Truck } from "lucide-react";
import { Header } from "./components/Header";
import { Controls } from "./components/Controls";
import { KpiRow } from "./components/KpiRow";
import { Panel } from "./components/Panel";
import { ForecastChart } from "./components/ForecastChart";
import { InterpretationPanel } from "./components/InterpretationPanel";
import { MetricsPanel } from "./components/MetricsPanel";
import { ForecastTable } from "./components/ForecastTable";
import { TrendSeasonality } from "./components/TrendSeasonality";
import { FeaturesView } from "./components/FeaturesView";
import { DataPanel } from "./components/DataPanel";
import { MIN_MONTHS, useForecast } from "./engine/useForecast";
import { useInterpretation } from "./llm/useInterpretation";
import { monthLong } from "./lib/format";
import type { ModelKey } from "./types";

export default function App() {
  const fc = useForecast();
  const [viewing, setViewing] = useState<ModelKey | "all">("all");
  const llm = useInterpretation(fc.result, viewing, fc.engine.state === "ready");
  const { result } = fc;

  if (fc.loadError) return <Shell><p className="glass p-6 text-rose-300">{fc.loadError}</p></Shell>;
  if (!result) return <Shell><div className="glass h-64 animate-pulse" /></Shell>;

  const viewingLabel = viewing === "all" ? "All models" : result.models[viewing].label;

  return (
    <Shell engine={fc.engine}>
      <Controls
        result={result} settings={fc.settings} seriesLength={fc.series.length} viewing={viewing}
        setViewing={setViewing} update={fc.updateSettings} nextFeed={fc.nextFeedMonth}
        onAdvance={fc.advanceMonth} computing={fc.computing} engineReady={fc.engine.state === "ready"}
      />
      {fc.error && <p className="glass border-rose-400/30 px-4 py-3 text-sm text-rose-300" role="alert">Engine error: {fc.error}</p>}

      <KpiRow result={result} viewing={viewing} />

      <Panel
        title="Actual vs predicted sales"
        task="Tasks 3 · 4 · 6"
        icon={<LineChart size={18} />}
        subtitle={<>Trained on {monthLong(result.series[0].month)} – {monthLong(result.split.train_end)}, tested on the
          next {result.split.test_months} month(s) (chronological split), then refitted on all data to forecast {result.settings.horizon} month(s) ahead.</>}
      >
        <ForecastChart result={result} viewing={viewing} />
      </Panel>

      <Panel
        title="AI interpretation of the live results"
        task="Task 7 · LLM"
        icon={<Sparkles size={18} />}
        subtitle="Generated by an LLM from the numbers on this page right now; it updates when data or settings change. Every figure is checked against the computed results."
      >
        <InterpretationPanel state={llm} setAuto={llm.setAuto} regenerate={llm.regenerate}
          currentVersion={result.data_version} viewingLabel={viewingLabel} />
      </Panel>

      <Panel title="Model performance: MAPE and WAPE" task="Task 5" icon={<BarChart3 size={18} />}
        subtitle="All models scored on the same test months and horizon.">
        <MetricsPanel result={result} viewing={viewing} />
      </Panel>

      <Panel title={`Next ${result.settings.horizon}-month forecast`} task="Task 4" icon={<Truck size={18} />}
        subtitle="Point forecast and 95% range for production and distribution planning.">
        <ForecastTable result={result} viewing={viewing} />
      </Panel>

      <Panel title="Trend and seasonality" icon={<TrendingUp size={18} />}
        subtitle="How much of the month-to-month movement is trend, season, or just month length.">
        <TrendSeasonality result={result} />
      </Panel>

      <Panel title="Feature engineering" task="Task 1" icon={<Layers size={18} />}
        subtitle="Lag features and seasonal indicators, exactly as the models receive them.">
        <FeaturesView result={result} />
      </Panel>

      <Panel id="data" title="Real-time data" icon={<Database size={18} />}
        subtitle="New actuals re-run every model, metric and the AI interpretation.">
        <DataPanel
          series={fc.series} nextFeed={fc.nextFeedMonth} canRemove={fc.series.length > MIN_MONTHS}
          onAdvance={fc.advanceMonth} onAdd={fc.addMonth} onEdit={fc.editMonth}
          onRemoveLast={fc.removeLast} onReset={fc.reset}
        />
      </Panel>

      <footer className="pb-10 pt-2 text-center text-xs text-ink-mute">
        Data: Kaggle “Beverage Sales” (SWillm, 2025, MIT), synthetic. Volvic Touch flavored water stands in for the new product; 2021 is its first year.
        Models run in your browser (Python via Pyodide); the LLM is called through a server-side function.
      </footer>
    </Shell>
  );
}

function Shell({ children, engine }: { children: React.ReactNode; engine?: ReturnType<typeof useForecast>["engine"] }) {
  return (
    <>
      <div className="backdrop" aria-hidden />
      <main className="mx-auto flex max-w-7xl flex-col gap-6 px-4 sm:px-6">
        <Header engine={engine ?? { state: "loading", message: "Loading data" }} />
        {children}
      </main>
    </>
  );
}
